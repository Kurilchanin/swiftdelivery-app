export const DICTS = { en, ru, es, fa, ar }

// Languages written right-to-left. The app sets <html dir> from this (main.jsx).
const RTL_LANGS = new Set(['fa', 'ar'])
export const DIR = RTL_LANGS.has(LANG) ? 'rtl' : 'ltr'

// Translate one key. Falls back to English, then to the key itself. `params`
// fills {name} placeholders in the string.
export function t(key, params) {
  const dict = DICTS[LANG] || en
  let s = dict[key]
  if (s == null) s = en[key]
  if (s == null) return key
  if (params) {
    for (const name in params) {
      s = s.split('{' + name + '}').join(String(params[name]))
    }
  }
  return s
}

// Plural-aware amount: returns "n word" with the right form. `forms` holds the
// word forms for the ACTIVE language, in the order of PLURAL_CATS for that
// language:
//   en/es/fa — [one, other]                e.g. ['day', 'days']
//   ru       — [one, few, many]            e.g. ['день', 'дня', 'дней']
//   ar       — [zero, one, two, few, many, other]  (Arabic has six forms)
// Pass the forms for the active language; callers read them from a small table
// (see DURATION_WORDS) so each unit's forms live in one place.
const PLURAL = {
  en: new Intl.PluralRules('en'),
  ru: new Intl.PluralRules('ru'),
  es: new Intl.PluralRules('es'),
  fa: new Intl.PluralRules('fa'),
  ar: new Intl.PluralRules('ar'),
}
// The plural categories each language uses, in the order our `forms` arrays
// follow. `select()` returns one of these; its position is the form index.
const PLURAL_CATS = {
  en: ['one', 'other'],
  ru: ['one', 'few', 'many'],
  es: ['one', 'other'],
  fa: ['one', 'other'],
  ar: ['zero', 'one', 'two', 'few', 'many', 'other'],
}
export function plural(n, forms) {
  const rules = PLURAL[LANG] || PLURAL.en
  const cats = PLURAL_CATS[LANG] || PLURAL_CATS.en
  let idx = cats.indexOf(rules.select(n))
  if (idx < 0) idx = forms.length - 1 // category we did not list → last form
  return n + ' ' + (forms[idx] ?? forms[forms.length - 1])
}

// Word forms per language for the units we show. Keyed by [language][unit]; each
// array follows PLURAL_CATS for that language. Persian does not change the noun
// after a number, so both forms are the same.
const DURATION_WORDS = {
  en: { day: ['day', 'days'], hour: ['hour', 'hours'], min: ['min', 'min'] },
  ru: { day: ['день', 'дня', 'дней'], hour: ['час', 'часа', 'часов'], min: ['мин', 'мин', 'мин'] },
  es: { day: ['día', 'días'], hour: ['hora', 'horas'], min: ['min', 'min'] },
  fa: { day: ['روز', 'روز'], hour: ['ساعت', 'ساعت'], min: ['دقیقه', 'دقیقه'] },
  ar: {
    day: ['يوم', 'يوم', 'يومين', 'أيام', 'يوماً', 'يوم'],
    hour: ['ساعة', 'ساعة', 'ساعتين', 'ساعات', 'ساعة', 'ساعة'],
    min: ['دقيقة', 'دقيقة', 'دقيقتين', 'دقائق', 'دقيقة', 'دقيقة'],
  },
}
// "2 days" / "2 дня" — the count plus the right plural form of a duration unit.
export function durationWords(n, unit) {
  const table = DURATION_WORDS[LANG] || DURATION_WORDS.en
  return plural(n, table[unit])
}

// Short one-letter unit suffixes for compact countdowns ("2d 3h" / "2д 3ч").
const DURATION_SHORT = {
  en: { d: 'd', h: 'h', m: 'm', s: 's' },
  ru: { d: 'д', h: 'ч', m: 'м', s: 'с' },
  es: { d: 'd', h: 'h', m: 'm', s: 's' },
  fa: { d: 'ر', h: 'س', m: 'د', s: 'ث' },
  ar: { d: 'ي', h: 'س', m: 'د', s: 'ث' },
}
export function shortUnit(unit) {
  return (DURATION_SHORT[LANG] || DURATION_SHORT.en)[unit]
}

